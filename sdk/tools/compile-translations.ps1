param(
 [Parameter(Mandatory=$true)][string]$Catalog,
 [Parameter(Mandatory=$true)][string]$Output,
 [Parameter(Mandatory=$true)][ValidatePattern('^[A-Za-z_][A-Za-z0-9_]*$')][string]$Symbol
)
$ErrorActionPreference='Stop'
$utf8=[Text.UTF8Encoding]::new($false,$true)
$data=$utf8.GetString([IO.File]::ReadAllBytes((Resolve-Path -LiteralPath $Catalog))) | ConvertFrom-Json
$languages=@('en','fr','it','de','es','ja','ko','pl','pt-br','ru','zh-cn','zh-tw','tr','uk','th')
if (@(Compare-Object $languages @($data.PSObject.Properties.Name)).Count) { throw 'Catalogue must contain exactly all 15 supported interface languages.' }
$keys=@($data.en.PSObject.Properties.Name)
if (!$keys.Count) { throw 'Empty catalogue' }
$lines=[Collections.Generic.List[string]]::new()
$lines.Add('// Generated by sdk/tools/compile-translations.ps1. Edit the JSON catalogue.')
$lines.Add('#pragma once')
$lines.Add('inline constexpr enshrouded::i18n::Translation '+$Symbol+'[] = {')
foreach($locale in $languages) {
 if (@(Compare-Object $keys @($data.$locale.PSObject.Properties.Name)).Count) { throw "Missing or unexpected keys: $locale" }
 foreach($key in $keys) {
  $value=$data.$locale.$key
  if ($key -notmatch '^[a-z][a-z0-9_.]*$' -or $value -isnot [string] -or [string]::IsNullOrWhiteSpace($value) -or $value -match '[\x00-\x09\x0b-\x1f\uFFFD]' -or $utf8.GetByteCount($value) -gt 4096) { throw "Invalid translation: $locale/$key" }
  $expected=@([regex]::Matches($data.en.$key,'</?b>|\{[a-z0-9_]+\}') | ForEach-Object {$_.Value})
  $actual=@([regex]::Matches($value,'</?b>|\{[a-z0-9_]+\}') | ForEach-Object {$_.Value})
  if (($expected -join '|') -cne ($actual -join '|')) { throw "Markup or placeholders differ: $locale/$key" }
  $quoted=ConvertTo-Json -InputObject $value -Compress
  $lines.Add('{"'+$locale+'","'+$key+'",'+$quoted+'},')
 }
}
$lines.Add('};')
[IO.File]::WriteAllLines([IO.Path]::GetFullPath($Output),$lines,$utf8)
Write-Output ("Validated {0} languages x {1} keys: {2}" -f $languages.Count,$keys.Count,$Symbol)
